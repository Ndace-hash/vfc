-- Phase 2: the shop. Products, size variants, orders and shop settings.
-- Run once in the Supabase SQL editor, after 0001. See docs/plans/public-site.md.
--
-- Money is stored as whole kobo in bigint (₦1 = 100 kobo): exact, and the
-- unit Paystack takes and returns.

begin;

-- ---------------------------------------------------------------------------
-- Products and variants
-- ---------------------------------------------------------------------------

create table public.products (
	id bigint generated always as identity primary key,
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now(),
	-- used in the URL: /shop/home-jersey-2026
	slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
	name text not null check (length(trim(name)) > 0),
	description text not null default '',
	price_kobo bigint not null check (price_kobo >= 0),
	-- what the variant choice is called on the product page: "Size", "Colour"
	option_name text not null default 'Size',
	-- public URLs in the images bucket (products/ folder); the first is the cover
	image_urls text[] not null default '{}',
	-- new products start hidden, so they can be finished before going live
	is_active boolean not null default false,
	-- shown in the home page shop section
	is_featured boolean not null default false,
	display_order integer not null default 0
);

create table public.product_variants (
	id bigint generated always as identity primary key,
	-- deleting a product deletes its variants, unless an order uses one (see order_items)
	product_id bigint not null references public.products (id) on delete cascade,
	-- "S", "M", "XL", "One size"
	label text not null check (length(trim(label)) > 0),
	stock integer not null default 0 check (stock >= 0),
	display_order integer not null default 0,
	is_active boolean not null default true,
	-- also serves as the index for the product_id foreign key
	unique (product_id, label)
);

alter table public.products enable row level security;
alter table public.product_variants enable row level security;

create policy products_public_read on public.products
	for select
	to anon, authenticated
	using (is_active);

create policy product_variants_public_read on public.product_variants
	for select
	to anon, authenticated
	using (
		is_active
		and exists (
			select 1 from public.products p
			where p.id = product_id and p.is_active
		)
	);

-- ---------------------------------------------------------------------------
-- Orders
-- ---------------------------------------------------------------------------

create table public.orders (
	id bigint generated always as identity primary key,
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now(),
	-- shown to the customer and sent to Paystack as the transaction reference,
	-- e.g. VFC-7K2M9QXA; generated by the server from an unambiguous alphabet
	reference text not null unique,
	-- pending_payment: created at checkout, Paystack has not confirmed payment
	-- paid -> ready -> completed: staff move it along in the admin
	-- needs_attention: paid, but the amount was wrong or stock ran out; refund or restock
	-- cancelled: abandoned or refunded
	status text not null default 'pending_payment' check (
		status in ('pending_payment', 'paid', 'ready', 'completed', 'needs_attention', 'cancelled')
	),
	customer_name text not null check (length(trim(customer_name)) between 1 and 200),
	customer_email text not null check (customer_email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
	customer_phone text not null check (length(trim(customer_phone)) between 1 and 40),
	fulfilment text not null check (fulfilment in ('pickup', 'delivery')),
	delivery_address text,
	subtotal_kobo bigint not null check (subtotal_kobo >= 0),
	delivery_fee_kobo bigint not null default 0 check (delivery_fee_kobo >= 0),
	total_kobo bigint generated always as (subtotal_kobo + delivery_fee_kobo) stored,
	paid_at timestamptz,
	paystack_transaction_id bigint,
	-- why the order needs attention, for staff
	attention_reason text,
	constraint orders_delivery_address_check
		check (fulfilment = 'pickup' or length(trim(coalesce(delivery_address, ''))) > 0)
);

-- the admin Orders list, filtered by status, newest first
create index orders_status_created_idx on public.orders (status, created_at desc);

create table public.order_items (
	id bigint generated always as identity primary key,
	order_id bigint not null references public.orders (id) on delete cascade,
	-- restrict: a variant that has been ordered can't be deleted, only hidden,
	-- so order history stays intact
	variant_id bigint not null references public.product_variants (id) on delete restrict,
	-- copied at checkout, so later edits to the product don't change past orders
	product_name text not null,
	variant_label text not null,
	unit_price_kobo bigint not null check (unit_price_kobo >= 0),
	quantity integer not null check (quantity between 1 and 20),
	-- one line per variant; also serves as the index for the order_id foreign key
	unique (order_id, variant_id)
);

create index order_items_variant_id_idx on public.order_items (variant_id);

-- customer details: no browser access at all, only the server
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
revoke all on public.orders from anon, authenticated;
revoke all on public.order_items from anon, authenticated;

-- ---------------------------------------------------------------------------
-- Shop settings (a single row, edited in the admin)
-- ---------------------------------------------------------------------------

create table public.shop_settings (
	-- always true: the table can only ever hold one row
	id boolean primary key default true check (id),
	updated_at timestamptz not null default now(),
	pickup_address text not null default 'Pickup address to be confirmed',
	-- flat fee for delivery within Lagos
	delivery_fee_kobo bigint not null default 0 check (delivery_fee_kobo >= 0),
	outside_lagos_message text not null default
		'We currently deliver within Lagos only. Contact us to arrange delivery elsewhere.'
);

insert into public.shop_settings default values on conflict (id) do nothing;

alter table public.shop_settings enable row level security;
revoke all on public.shop_settings from anon, authenticated;

-- ---------------------------------------------------------------------------
-- Confirming a payment
-- ---------------------------------------------------------------------------

-- Called by the server once Paystack confirms a payment, from both the
-- webhook and the customer's return to the site. Safe to call more than once
-- for the same order: only the first call changes anything.
--
-- In one transaction it checks the amount paid, checks there is still enough
-- stock, takes the stock, and marks the order paid. If the amount is wrong or
-- stock has run out (two people paid for the last shirt), nothing is taken
-- and the order is marked needs_attention for staff to refund or restock.
--
-- Returns the order's status after the call.
create or replace function public.mark_order_paid(
	p_reference text,
	p_transaction_id bigint,
	p_amount_kobo bigint
)
returns text
language plpgsql
set search_path = ''
as $$
declare
	v_order public.orders%rowtype;
	v_short integer;
begin
	select * into v_order
	from public.orders
	where reference = p_reference
	for update;

	if not found then
		raise exception 'No order with reference %', p_reference;
	end if;

	-- already handled (Paystack can send the same event more than once)
	if v_order.status <> 'pending_payment' then
		return v_order.status;
	end if;

	if p_amount_kobo <> v_order.total_kobo then
		update public.orders
		set status = 'needs_attention',
			paid_at = now(),
			paystack_transaction_id = p_transaction_id,
			attention_reason = format('Paid %s kobo but the order total is %s kobo', p_amount_kobo, v_order.total_kobo),
			updated_at = now()
		where id = v_order.id;
		return 'needs_attention';
	end if;

	-- lock this order's variants in id order, so two payments for the same
	-- items queue up instead of deadlocking
	perform 1
	from public.product_variants v
	where v.id in (select i.variant_id from public.order_items i where i.order_id = v_order.id)
	order by v.id
	for update;

	select count(*) into v_short
	from public.order_items i
	join public.product_variants v on v.id = i.variant_id
	where i.order_id = v_order.id
		and v.stock < i.quantity;

	if v_short > 0 then
		update public.orders
		set status = 'needs_attention',
			paid_at = now(),
			paystack_transaction_id = p_transaction_id,
			attention_reason = format('Not enough stock for %s item(s) when payment arrived: refund or restock', v_short),
			updated_at = now()
		where id = v_order.id;
		return 'needs_attention';
	end if;

	update public.product_variants v
	set stock = v.stock - i.quantity
	from public.order_items i
	where i.order_id = v_order.id
		and v.id = i.variant_id;

	update public.orders
	set status = 'paid',
		paid_at = now(),
		paystack_transaction_id = p_transaction_id,
		updated_at = now()
	where id = v_order.id;

	return 'paid';
end;
$$;

-- only the server (service_role, via the secret key) may confirm payments
revoke execute on function public.mark_order_paid(text, bigint, bigint) from public, anon, authenticated;
grant execute on function public.mark_order_paid(text, bigint, bigint) to service_role;

commit;
